    DHCP_engine=$engine; DHCP_enabled=yes
    case $engine in
        kea) DHCP_service_name=$keaservice ;;
        dnsmasq) DHCP_service_name=$dnsmasqservice ;;
    esac
    configureDHCP >/dev/null 2>&1
    log=$(cat "$SYSLOG")
    case $engine in
        kea) has "$log" "rc-service fog-dnsmasq stop" "OpenRC kea: fog-dnsmasq is stopped"
             has "$log" "rc-update del fog-dnsmasq default" "OpenRC kea: fog-dnsmasq leaves the default runlevel" ;;
        dnsmasq) has "$log" "rc-service $keaservice stop" "OpenRC dnsmasq: Kea is stopped"
                 has "$log" "rc-update del $keaservice default" "OpenRC dnsmasq: Kea leaves the default runlevel" ;;
    esac
    has "$log" "rc-service $DHCP_service_name start" "OpenRC $engine: its own service is started"
    # Alpine has no ISC package, so FOG never owns the ISC service there.
    [[ -n $iscservice && -z $(grep -F "rc-service $iscservice " "$SYSLOG") ]] && ok "OpenRC $engine: the ISC service is not touched" \
        || bad "OpenRC $engine: the ISC service ($iscservice) was touched"
    [[ -z $(grep -E ' dnsmasq( |$)' "$SYSLOG") ]] && ok "OpenRC $engine: the distro dnsmasq is never named" \
        || bad "OpenRC $engine: the distro dnsmasq service was touched"
done
