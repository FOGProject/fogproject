echo "== firewall: 4011/udp only in proxy mode =="
ftppasvmin=40000; ftppasvmax=40100; mcastportmin=50000; mcastportmax=50100
DHCP_enabled=yes; DHCP_proxy=""
is "$(_firewallPortList | grep -c '^4011/udp')" "0" "full mode: 4011/udp is not opened"
DHCP_proxy=yes
is "$(_firewallPortList | grep -c '^4011/udp')" "1" "proxy mode: 4011/udp is in the port list"
is "$(_firewallPortList | grep -c '^67/udp')" "1" "proxy mode: 67/udp stays"
