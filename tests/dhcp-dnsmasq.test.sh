echo "== engine switches never touch the distro dnsmasq service =="
# The real configureDHCP, with the config writers stubbed so only the service
# handling is exercised. Every systemctl call lands in $SYSLOG. This runs last
# because the stubs replace the real writers.
configureKeaDHCP() { return 0; }
configureDnsmasqDHCP() { return 0; }
writeKeaSample() { :; }
dhcpconfig="$WORK/dhcpd.conf"; : > "$dhcpconfig"
dhcpconfigother=""
iscservice=isc-dhcp-server; keaservice=kea-dhcp4-server
for engine in isc kea dnsmasq; do
    : > "$SYSLOG"
    DHCP_engine=$engine; DHCP_enabled=yes
    case $engine in
        isc) DHCP_service_name=$iscservice ;;
        kea) DHCP_service_name=$keaservice ;;
        dnsmasq) DHCP_service_name=$dnsmasqservice ;;
    esac
    configureDHCP >/dev/null 2>&1
    log=$(cat "$SYSLOG")
    has "$log" "start $DHCP_service_name" "$engine: its own service is started"
    # Every logged call ends in a service name; none may end in bare "dnsmasq".
    [[ -z $(grep -E ' dnsmasq$' "$SYSLOG") ]] && ok "$engine: the distro dnsmasq is never named" \
        || bad "$engine: the distro dnsmasq service was touched"
    case $engine in
        isc|kea) has "$log" "stop fog-dnsmasq" "$engine: fog-dnsmasq is stopped on a switch"
                 has "$log" "disable fog-dnsmasq" "$engine: fog-dnsmasq is disabled on a switch" ;;
        dnsmasq) has "$log" "stop $iscservice" "dnsmasq: ISC is stopped on a switch"
                 has "$log" "stop $keaservice" "dnsmasq: Kea is stopped on a switch" ;;
    esac
done
[[ -d $dnsmasqleasedir ]] && ok "dnsmasq: the lease directory exists after configureDHCP" || bad "no lease directory"

echo "== OpenRC: the same switches on Alpine =="
# No systemd. rc-service and rc-update are logged in place of the real tools.
systemctl=no; FOG_os_id=3
