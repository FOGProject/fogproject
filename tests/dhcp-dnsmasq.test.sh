#!/bin/bash
#
# Guards the dnsmasq DHCP engine (FOGProject/fogproject#2195, phase 1).
#
#   tests/dhcp-dnsmasq.test.sh
#
# --dhcp-engine dnsmasq makes configureDnsmasqDHCP() write /etc/fog/dnsmasq.conf.
# It also writes a fog-dnsmasq service that runs this file.
# The mode is a full DHCP server, or proxyDHCP with --dhcp-proxy.
# A proxy hands out no addresses.
# FOG runs its own dnsmasq instance.
# These are easy to break, and they fail far from the cause:
#
#   * port=0. Without it dnsmasq also binds port 53 and fights systemd-resolved.
#   * bind-interfaces. It lets this instance share the machine with the admin's
#     own dnsmasq. Without it both fight over the wildcard socket.
#   * The proxy keyword. Without it a proxy becomes a second DHCP server.
#     That server hands out addresses on a network that already has one.
#   * The boot files. They come from _biosBootFile and _uefiBootFile.
#     That is the source the Kea and ISC configs use. No name is typed here.
#   * The --conf-file in the unit. It stops this instance reading the admin's
#     /etc/dnsmasq.conf. It also stops the admin's instance reading ours.
#   * The distro's dnsmasq service. FOG starts, stops, enables and disables
#     fog-dnsmasq only. The distro's service belongs to the admin.
#   * Proxy mode. It sets no pool, router or DNS. --no-dhcp-proxy never
#     turns a proxy into a full DHCP server by itself.
#   * Choosing dnsmasq on its own. It is opt-in only.
#
# Where dnsmasq is installed, both generated configs go through `dnsmasq --test`.
# That check needs no root.
#
# No install, no network, no root.
#
# Exit status 0 = pass, 1 = fail.

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/.." && pwd)"
FUNCS="$REPO/lib/common/functions.sh"
UNINSTALL="$REPO/lib/common/uninstall.sh"
INSTALLER="$REPO/bin/installfog.sh"

for f in "$FUNCS" "$UNINSTALL" "$INSTALLER"; do
    [[ -f $f ]] || { echo "ERROR: $f not found" >&2; exit 1; }
done

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

PASS=0
FAIL=0
ok()    { PASS=$((PASS + 1)); printf '  ok    %s\n' "$1"; }
bad()   { FAIL=$((FAIL + 1)); printf '  FAIL  %s\n' "$1"; }
is()    { [[ "$1" == "$2" ]] && ok "$3" || bad "$3 (expected '$2', got '$1')"; }
has()   { [[ $1 == *"$2"* ]] && ok "$3" || bad "$3 (not found: '$2')"; }
hasnt() { [[ $1 != *"$2"* ]] && ok "$3" || bad "$3 (unexpectedly present: '$2')"; }

error_log="$WORK/error.log"
: > "$error_log"
# shellcheck source=/dev/null
. "$FUNCS" >/dev/null 2>&1
# shellcheck source=/dev/null
. "$UNINSTALL" >/dev/null 2>&1

dots() { :; }
errorStat() { :; }
exitFail=1

# Staged signed chain, so the UEFI names are the shim ones; "bare" has none and
# gets the unsigned fallback. The expected names are always read back from
# _uefiBootFile/_biosBootFile, never typed in this test.
mkdir -p "$WORK/staged/secureboot" "$WORK/bare"
: > "$WORK/staged/secureboot/snponly-shimx64.efi"
BOOT_dhcp_delay_seconds=0
tftpdirsrc="$WORK/staged"

NET_interface=eth0
NET_fog_server_ip=192.168.56.1
NET_subnet_mask=255.255.255.0
DHCP_range_start=192.168.56.101
DHCP_range_end=192.168.56.200
DHCP_router=192.168.56.254
DHCP_dns_server_ip=192.168.56.2
DHCP_enabled=yes
DHCP_engine=dnsmasq
dnsmasqconfig="$WORK/fog/dnsmasq.conf"
dnsmasqservice=fog-dnsmasq
dnsmasqleasedir="$WORK/lease"
dnsmasqunit="$WORK/fog-dnsmasq.service"
dnsmasqinit="$WORK/init-fog-dnsmasq"
systemctl=yes
timestamp=T1

# Every systemctl call is logged and none reaches the machine. is-active and
# is-enabled answer "yes" so the stop and disable paths run.
SYSLOG="$WORK/systemctl.log"
: > "$SYSLOG"
systemctl() {
    echo "$*" >> "$SYSLOG"
    # Everything is running and enabled except the service being set up, so a
    # switch has something to stop and the new service something to start.
    case $1 in
        is-active|is-enabled) [[ ${@: -1} != "$DHCP_service_name" ]] ;;
        *) return 0 ;;
    esac
}
# A host with SELinux enforcing would run semanage on this machine's policy.
selinuxenabled() { return 1; }

# Command substitution strips the final newline, which would hide the last line
# from the "\nline\n" matches below, so it is put back.
cfg() { cat "$dnsmasqconfig"; echo x; }
have_dnsmasq() { command -v dnsmasq >/dev/null 2>&1; }

echo "== full mode =="
DHCP_proxy=""
configureDnsmasqDHCP >/dev/null
rc=$?
is "$rc" "0" "configureDnsmasqDHCP succeeds"
out=$(cfg)
has "$out" "# Generated by FOG" "header says FOG generated it"
has "$out" $'\nport=0\n' "DNS is off (port=0)"
has "$out" $'\ninterface=eth0\n' "bound to the FOG interface"
has "$out" $'\nbind-interfaces\n' "bind-interfaces"
has "$out" $'\nlog-dhcp\n' "log-dhcp"
hasnt "$out" "enable-tftp" "dnsmasq's own TFTP stays off"
has "$out" $'\ndhcp-leasefile='"$WORK/lease"$'/dnsmasq.leases\n' "own lease file"
has "$out" $'\npid-file=/run/fog-dnsmasq.pid\n' "own PID file, not the distro's /run/dnsmasq.pid"
hasnt "$out" "conf-dir" "no conf-dir"
hasnt "$out" "proxy" "full mode has no proxy keyword"
has "$out" $'\ndhcp-range=192.168.56.101,192.168.56.200,255.255.255.0,6h\n' "address range, mask and lease time"
has "$out" $'\ndhcp-option=option:router,192.168.56.254\n' "router option when valid"
has "$out" $'\ndhcp-option=option:dns-server,192.168.56.2\n' "DNS option when valid"
bios=$(_biosBootFile); u32=$(_uefiBootFile i386); x64=$(_uefiBootFile x64); a64=$(_uefiBootFile arm64)
has "$out" $'\ndhcp-boot=tag:fog-bios,'"${bios},,192.168.56.1"$'\n' "BIOS boot file from _biosBootFile"
has "$out" $'\ndhcp-boot=tag:fog-uefi32,'"${u32},,192.168.56.1"$'\n' "UEFI 32 boot file from _uefiBootFile"
has "$out" $'\ndhcp-boot=tag:fog-x64,'"${x64},,192.168.56.1"$'\n' "UEFI x64 boot file from _uefiBootFile"
has "$out" $'\ndhcp-boot=tag:fog-arm64,'"${a64},,192.168.56.1"$'\n' "arm64 boot file from _uefiBootFile"
has "$x64" "secureboot/snponly-shimx64.efi" "staged tree: x64 is the signed shim"
for n in 7 8 9; do
    has "$out" $'\ndhcp-match=set:fog-x64,option:client-arch,'"$n"$'\n' "arch $n -> x64"
done
for n in 2 6; do
    has "$out" $'\ndhcp-match=set:fog-uefi32,option:client-arch,'"$n"$'\n' "arch $n -> UEFI 32"
done
has "$out" $'\ndhcp-match=set:fog-bios,option:client-arch,0\n' "arch 0 -> BIOS"
has "$out" $'\ndhcp-match=set:fog-arm64,option:client-arch,11\n' "arch 11 -> arm64"
is "$(stat -c %a "$dnsmasqconfig")" "644" "mode is 0644"
if have_dnsmasq; then
    dnsmasq --test --conf-file="$dnsmasqconfig" >/dev/null 2>&1
    is "$?" "0" "dnsmasq --test accepts the full-mode config"
else
    echo "  skip  dnsmasq is not installed: no dnsmasq --test"
fi

# Router and DNS are written only when each is a real address. "# No router
# added" is what the installer stores when the admin declines one.
DHCP_router="# No router added"; DHCP_dns_server_ip=""
configureDnsmasqDHCP >/dev/null
out=$(cfg)
hasnt "$out" "option:router" "no router line without a valid router"
hasnt "$out" "option:dns-server" "no DNS line without a valid DNS server"
DHCP_router=192.168.56.254; DHCP_dns_server_ip=192.168.56.2

echo "== unsigned fallback =="
tftpdirsrc="$WORK/bare"
configureDnsmasqDHCP >/dev/null
out=$(cfg)
has "$out" $'\ndhcp-boot=tag:fog-x64,snponly.efi,,192.168.56.1\n' "no staged chain: x64 falls back to snponly.efi"
has "$out" $'\ndhcp-boot=tag:fog-arm64,arm64-efi/snponly.efi,,192.168.56.1\n' "no staged chain: arm64 falls back"
tftpdirsrc="$WORK/staged"

echo "== proxy mode =="
DHCP_proxy=yes
configureDnsmasqDHCP >/dev/null
is "$?" "0" "configureDnsmasqDHCP succeeds in proxy mode"
out=$(cfg)
has "$out" $'\nport=0\n' "DNS is off (port=0)"
has "$out" $'\ndhcp-range=192.168.56.0,proxy,255.255.255.0\n' "proxy range on the FOG network"
hasnt "$out" ",6h" "no address pool"
hasnt "$out" "dhcp-option" "no router or DNS option"
hasnt "$out" "enable-tftp" "dnsmasq's own TFTP stays off"
has "$out" $'\ndhcp-boot=tag:fog-x64,'"${x64},,192.168.56.1"$'\n' "dhcp-boot names the FOG server"
has "$out" $'\npxe-service=0,"Boot to FOG",'"${bios},192.168.56.1"$'\n' "pxe-service for BIOS"
for n in 7 8 9; do
    has "$out" $'\npxe-service='"$n"$',"Boot to FOG UEFI",'"${x64},192.168.56.1"$'\n' "pxe-service for arch $n"
done
has "$out" $'\npxe-service=11,"Boot to FOG ARM64",'"${a64},192.168.56.1"$'\n' "pxe-service for arm64"
if have_dnsmasq; then
    dnsmasq --test --conf-file="$dnsmasqconfig" >/dev/null 2>&1
    is "$?" "0" "dnsmasq --test accepts the proxy config"
fi
DHCP_proxy=""

echo "== backup beside dnsmasq.conf =="
# Content changed above, so the previous config was backed up, as .<timestamp>
# next to it, the way Kea's is.
timestamp=T2
configureDnsmasqDHCP >/dev/null
[[ -f "${dnsmasqconfig}.T2" ]] && ok "a changed config leaves a backup" || bad "no backup of the changed config"
timestamp=T3
configureDnsmasqDHCP >/dev/null
[[ ! -f "${dnsmasqconfig}.T3" ]] && ok "an unchanged config leaves no backup" || bad "backup kept for an unchanged config"

echo "== the fog-dnsmasq service =="
unit=$(cat "$dnsmasqunit"; echo x)
bin=$(command -v dnsmasq || echo /usr/sbin/dnsmasq)
has "$unit" $'\nExecStart='"$bin -k --conf-file=$dnsmasqconfig"$'\n' "ExecStart runs in the foreground on FOG's own config"
has "$unit" $'\nExecStartPre='"$bin --test --conf-file=$dnsmasqconfig"$'\n' "ExecStartPre validates the same config"
has "$unit" $'\nAfter=network-online.target\n' "starts after the network is online"
has "$unit" $'\nWantedBy=multi-user.target\n' "enabled into multi-user.target"
has "$(cat "$SYSLOG")" "daemon-reload" "systemd is told about the new unit"
hasnt "$(grep -v '^#' "$dnsmasqunit")" "/etc/dnsmasq.conf" "the unit never names the distro's config"
# The OpenRC script is Alpine's. No systemd there.
systemctl=no; FOG_os_id=3
configureDnsmasqDHCP >/dev/null
init=$(cat "$dnsmasqinit")
has "$init" "#!/sbin/openrc-run" "OpenRC: an openrc-run script"
has "$init" "command=$bin" "OpenRC: the dnsmasq binary"
has "$init" "command_args=\"-k --conf-file=$dnsmasqconfig\"" "OpenRC: foreground, on FOG's own config"
has "$init" "command_background=true" "OpenRC: backgrounded by OpenRC"
has "$init" "pidfile=/run/fog-dnsmasq.pid" "OpenRC: the same PID file as the config"
[[ -x $dnsmasqinit ]] && ok "OpenRC: the script is executable" || bad "OpenRC script is not executable"
systemctl=yes; FOG_os_id=""
# No systemd and no OpenRC: refuse, and say why, rather than write nothing.
systemctl=no
out=$(configureDnsmasqDHCP 2>&1); rc=$?
is "$rc" "1" "no systemd and no OpenRC: configureDnsmasqDHCP fails"
has "$out" "needs systemd or OpenRC" "and says why"
systemctl=yes

echo "== uninstall =="
timestamp=T9
DHCP_engine=dnsmasq; DHCP_proxy=""; configureDnsmasqDHCP >/dev/null
mkdir -p "$dnsmasqleasedir"
: > "$SYSLOG"
removeDnsmasqEngine >/dev/null
[[ ! -e $dnsmasqunit ]] && ok "the unit is removed" || bad "the unit is still there"
[[ ! -e $dnsmasqconfig ]] && ok "the config is removed" || bad "the config is still there"
[[ -z $(ls "${dnsmasqconfig}".[0-9]* 2>/dev/null) ]] && ok "its backups are removed" || bad "backups are still there"
[[ ! -d $dnsmasqleasedir ]] && ok "the lease directory is removed" || bad "the lease directory is still there"
has "$(cat "$SYSLOG")" "stop fog-dnsmasq" "fog-dnsmasq is stopped"
has "$(cat "$SYSLOG")" "disable fog-dnsmasq" "fog-dnsmasq is disabled"
hasnt "$(cat "$SYSLOG")" "stop dnsmasq"$'\n' "the distro dnsmasq is not stopped"
# The same uninstall on Alpine stops the service through OpenRC.
systemctl=no; FOG_os_id=3
rc-service() { echo "rc-service $*" >> "$SYSLOG"; }
rc-update() { echo "rc-update $*" >> "$SYSLOG"; }
configureDnsmasqDHCP >/dev/null
: > "$SYSLOG"
removeDnsmasqEngine >/dev/null
has "$(cat "$SYSLOG")" "rc-service fog-dnsmasq stop" "OpenRC uninstall: fog-dnsmasq is stopped"
has "$(cat "$SYSLOG")" "rc-update del fog-dnsmasq default" "OpenRC uninstall: fog-dnsmasq leaves the default runlevel"
[[ ! -e $dnsmasqinit ]] && ok "OpenRC uninstall: the script is removed" || bad "OpenRC uninstall: the script is still there"
unset -f rc-service rc-update
systemctl=yes; FOG_os_id=""

echo "== --dhcp-engine and --dhcp-proxy options =="
longopts=$(sed -n 's/^longopts="\(.*\)"$/\1/p' "$INSTALLER")
parsed=$(getopt -o "" -l "$longopts" -n test -- --dhcp-engine DNSMASQ --dhcp-proxy --no-dhcp-proxy 2>&1)
is "$parsed" " --dhcp-engine 'DNSMASQ' --dhcp-proxy --no-dhcp-proxy --" "getopt accepts the three options"
usagetext=$(sed -n '/^usage()/,/^}/p' "$INSTALLER")
for opt in dhcp-engine dhcp-proxy no-dhcp-proxy; do
    has "$usagetext" -- "--${opt}" "--${opt} is in the help text"
done
arm=$(sed -n '/^        --dhcp-engine)$/,/^            ;;$/p' "$INSTALLER")
[[ -n $arm ]] || { echo "ERROR: could not extract the --dhcp-engine arm" >&2; exit 1; }
usage() { :; }
parseeng() {
    ( sDHCP_engine=""
      eval "case \$1 in
$arm
esac"
      echo "engine=${sDHCP_engine}" ) 2>&1
}
is "$(parseeng --dhcp-engine isc)" "engine=isc" "isc is accepted"
is "$(parseeng --dhcp-engine KEA)" "engine=kea" "kea is accepted in any case"
is "$(parseeng --dhcp-engine dnsMasq)" "engine=dnsmasq" "dnsmasq is accepted in any case"
is "$(parseeng --dhcp-engine bind)" "--dhcp-engine must be isc, kea or dnsmasq" "anything else is refused"
is "$(parseeng --dhcp-engine "")" "--dhcp-engine must be isc, kea or dnsmasq" "an empty value is refused"

# The post-parse block: the engine override and the proxy rule, read from the
# installer so the test cannot drift from it.
block=$(sed -n '/^\[\[ -n \${sDHCP_engine} \]\]/,/^\[\[ -n \${sPKI_client_cert_dir} \]\]/p' "$INSTALLER" | sed '$d')
[[ -n $block ]] || { echo "ERROR: could not extract the engine/proxy block" >&2; exit 1; }
apply() {   # apply <saved engine> <flag engine> <flag proxy> [saved proxy] -> engine/proxy, or the error
    ( DHCP_engine="$1"; sDHCP_engine="$2"; sDHCP_proxy="$3"; DHCP_proxy="${4:-}"
      eval "$block"
      echo "engine=${DHCP_engine} proxy=${DHCP_proxy}" ) 2>&1
}
# The same block for --no-dhcp-proxy: <saved enabled> <pool flags given: yes|no> -> enabled and the one line.
applyno() {
    ( DHCP_engine=dnsmasq; sDHCP_engine=""; sDHCP_proxy=no; DHCP_proxy="${3-yes}"; DHCP_enabled="$1"
      sDHCP_range_start=""; sDHCP_range_end=""
      [[ $2 == yes ]] && { sDHCP_range_start=192.168.56.101; sDHCP_range_end=192.168.56.200; }
      eval "$block"
      echo "enabled=${DHCP_enabled} proxy=${DHCP_proxy}" ) 2>&1
}
is "$(applyno yes no)" " * --no-dhcp-proxy: FOG DHCP is turned off. Add -s and -e to serve addresses instead.
enabled=no proxy=" "--no-dhcp-proxy on a proxy install turns DHCP off by default"
is "$(applyno yes yes)" " * --no-dhcp-proxy: FOG now serves addresses itself (full DHCP, pool from -s/-e).
enabled=yes proxy=" "--no-dhcp-proxy with -s and -e serves addresses, and says so"
is "$(applyno yes no "")" "enabled=yes proxy=" "--no-dhcp-proxy on a non-proxy install changes nothing"
is "$(apply "" dnsmasq yes)" "engine=dnsmasq proxy=yes" "--dhcp-proxy with dnsmasq is accepted"
is "$(apply "" kea yes)" "--dhcp-proxy requires --dhcp-engine dnsmasq" "--dhcp-proxy with kea is a usage error"
is "$(apply "" isc yes)" "--dhcp-proxy requires --dhcp-engine dnsmasq" "--dhcp-proxy with isc is a usage error"
is "$(apply "" "" yes)" "--dhcp-proxy requires --dhcp-engine dnsmasq" "--dhcp-proxy with no engine is a usage error"
is "$(apply dnsmasq "" yes)" "engine=dnsmasq proxy=yes" "--dhcp-proxy with a saved dnsmasq engine is accepted"
is "$(apply dnsmasq "" no yes)" " * --no-dhcp-proxy: FOG DHCP is turned off. Add -s and -e to serve addresses instead.
engine=dnsmasq proxy=" "--no-dhcp-proxy turns proxy mode off"
is "$(apply dnsmasq "" "" yes)" "engine=dnsmasq proxy=yes" "a saved proxy setting is kept"
is "$(apply dnsmasq kea "" yes)" " * Note: proxyDHCP is dnsmasq only; clearing the saved --dhcp-proxy setting.
 * FOG DHCP is turned off. Add -s and -e to serve addresses with kea.
engine=kea proxy=" "switching away from dnsmasq clears a saved proxy setting"
# The switch must not make the new engine serve a default pool on a network
# that already has a DHCP server.
switchenabled() {   # switchenabled <pool flags given: yes|no> -> enabled after a proxy -> kea switch
    ( DHCP_engine=dnsmasq; sDHCP_engine=kea; sDHCP_proxy=""; DHCP_proxy=yes; DHCP_enabled=yes
      sDHCP_range_start=""; sDHCP_range_end=""
      [[ $1 == yes ]] && { sDHCP_range_start=192.168.56.101; sDHCP_range_end=192.168.56.200; }
      eval "$block" >/dev/null
      echo "enabled=${DHCP_enabled}" ) 2>&1
}
is "$(switchenabled no)" "enabled=no" "proxy -> kea without -s/-e turns FOG DHCP off"
is "$(switchenabled yes)" "enabled=yes" "proxy -> kea with -s/-e keeps FOG DHCP on"
is "$(apply kea "" "")" "engine=kea proxy=" "no flag: the saved engine stays"
is "$(apply kea dnsmasq "")" "engine=dnsmasq proxy=" "an explicit engine overrides the saved one"

echo "== dnsmasq is never chosen automatically =="
INSTALLED=""
pkgIsInstalled() { [[ " $INSTALLED " == *" $1 "* ]]; }
pkgIsAvailable() { return 0; }
dhcpname="isc-dhcp-server"; keapackage="kea-dhcp4-server"; keaservice="kea-dhcp4-server"
dnsmasqpackage="dnsmasq"; dnsmasqservice="fog-dnsmasq"
for installed in "" "isc-dhcp-server" "dnsmasq"; do
    INSTALLED="$installed"
    DHCP_engine=""; DHCP_enabled=yes; FOG_packages="bc isc-dhcp-server lftp"
    resolveDHCPEngine
    [[ $DHCP_engine != dnsmasq ]] && ok "no flag (installed: '${installed:-nothing}'): engine is $DHCP_engine, not dnsmasq" \
