use FOG\Base\System;

/*
 * Composer's PSR-4 loader for FOG\ => packages/web/src.
 *
 * Here, at file scope, because this is the one file every entry point
 * reaches: the web UI, the API, the 41 fog-client endpoints under service/,
 * status/, maintenance/, and all nine CLI daemons via
 * packages/service/lib/service_lib.php all arrive through
 * commons/base.inc.php -> require 'init.php'. There is no second bootstrap
 * to keep in step.
 *
 * Loading here also fixes the chain order for free. spl_autoload_register is
 * a queue, and this runs at include time while Initiator::autoload() is
 * registered later inside the constructor -- so a real namespaced class in
 * src/ is found by Composer first, and only a miss falls through to the
 * short-name bridge below. That is the right precedence: the bridge is a
 * compatibility shim, not the destination.
 *
 * Guarded because the file legitimately may not be there: a checkout that
 * has not run `composer install`, and -- the case that actually matters --
 * every server installed before this commit, whose web tree has no vendor/
 * until the next upgrade re-lays it. FOG must boot without it.
 */
$fogComposerAutoload = __DIR__ . DIRECTORY_SEPARATOR . '..'
    . DIRECTORY_SEPARATOR . 'vendor' . DIRECTORY_SEPARATOR . 'autoload.php';
if (is_readable($fogComposerAutoload)) {
    require_once $fogComposerAutoload;
}
unset($fogComposerAutoload);

class Initiator
{
    private static $sanitizeItems;

    private static function setSanitize(): void
    {
        if (!self::$sanitizeItems) {
            self::$sanitizeItems = function (&$val, $key): void {
                if (is_array($val)) {
                    array_walk($val, self::$sanitizeItems);
                    return;
                }

                if (is_string($val)) {
                    $val = trim(str_replace("\0", '', $val));
                }
            };
        }
    }

    /**
     * No native `mixed` type hint here on purpose. `mixed` is a real type only
     * from PHP 8.0; on 7.4 the parser reads it as a *class* name, so every call
     * throws an uncaught TypeError ("must be an instance of mixed") and the
     * request dies with a zero-byte 500 before any output. _verCheck() below
     * still admits 7.4, so that is a supported target. The (string) cast makes
     * the hint redundant anyway. Refs forums.fogproject.org topic 18204.
     */
    public static function e($value): string
    {
        return htmlspecialchars(
            (string)($value ?? ''),
            ENT_QUOTES | ENT_SUBSTITUTE,
            'UTF-8',
            false
        );
    }

    public function __construct()
    {
        // Use cookies only, no URL-based sessions
        ini_set('session.use_only_cookies', '1');
        ini_set('session.use_strict_mode', '1');

        // 'secure' is intentionally false so the same session cookie is valid
        // over both HTTP and HTTPS. If you want HTTPS-only, set this to true
        // and add a hard HTTP→HTTPS redirect at the web-server level so the
        // PHP session path is never reached over plain HTTP.
        session_set_cookie_params([
            'lifetime' => 0,
            'path'     => '/',
            'domain'   => '',            // default current host
            'secure'   => false,         // false = dual HTTP+HTTPS support
            'httponly' => true,
            'samesite' => 'Lax',
        ]);

        self::setSanitize();
        define('DS', DIRECTORY_SEPARATOR);
        define('BASEPATH', self::_determineBasePath());

        // The boot file-list cache (classFileList) needs the cache dir before
        // System.class.php loads. Define the constants here, guarded, so System
        // (the canonical, documented home for FOG_BASE_DIR) defers to these.
        //
        // GH-850: fogpaths.php is generated by the installer from its
        // $fogprogramdir, so a non-default base path reaches PHP instead of
        // being assumed. It is a bare define-only file precisely so it can be
        // pulled in here -- before the autoloader exists. Absent on a pre-850
        // install or a hand-copied web tree, in which case the /opt/fog
        // fallback below keeps the previous behavior.
        $fogPaths = __DIR__ . DS . 'fogpaths.php';
        if (is_readable($fogPaths)) {
            require_once $fogPaths;
        }
        if (!defined('FOG_BASE_DIR')) {
            define('FOG_BASE_DIR', '/opt/fog');
        }
        if (!defined('FOG_CACHE_DIR')) {
            define('FOG_CACHE_DIR', FOG_BASE_DIR . DS . 'cache');
        }
        // Fallback for the service log path. The configured value comes from
        // the SERVICE_LOG_PATH globalSetting; this is what the daemons and the
        // log viewer use when that is empty, and it mirrors the installer's
        // $servicelogs default.
        if (!defined('FOG_LOG_DIR')) {
            define('FOG_LOG_DIR', FOG_BASE_DIR . DS . 'log');
        }
        // The EXTERNAL plugin root (ADR 0009). Bundled plugins ship in the web
        // tree at BASEPATH/lib/plugins and are re-laid from the tarball on every
        // upgrade; third-party plugins live here instead, because
        // configureHttpd() does `rm -rf $webdirdest` and would delete anything
        // an admin had added. Living under FOG_BASE_DIR means it survives that
        // wipe BY CONSTRUCTION, the same property $customizationsDir relies on,
        // rather than by a backup-and-restore step that has to be re-made
        // correctly every upgrade.
        //
        // Absent on an install that has never used one; every consumer treats a
        // missing directory as "no external plugins" rather than an error.
        //
        // The final path segment MUST stay "plugins". FOGBase::fileitems()
        // decides whether a source file belongs to a plugin by looking for a
        // literal DS."plugins".DS in its path, which is how an external
        // plugin's hooks, pages and reports get picked up by the same
        // machinery as a bundled one. Point this somewhere not ending in
        // /plugins and those files are silently treated as core, which
        // bypasses the installed-plugin filter entirely.
        if (!defined('FOG_PLUGIN_DIR')) {
            define('FOG_PLUGIN_DIR', FOG_BASE_DIR . DS . 'plugins');
        }
        // FOG's own PHP session store. Created 0700 by the installer and
        // pointed at by _configureSessionStorage() below; see that method for
        // why FOG stops sharing the distro's session directory.
        if (!defined('FOG_SESSION_DIR')) {
            define('FOG_SESSION_DIR', FOG_BASE_DIR . DS . 'sessions');
        }

        $allpaths = array_unique(array_map('dirname', self::classFileList()));
        set_include_path(implode(PATH_SEPARATOR, $allpaths) . PATH_SEPARATOR . get_include_path());
        spl_autoload_extensions('.class.php,.page.php,.event.php,.hook.php,.report.php,.task.php');
        // An O(1) class-name => file map (see self::autoload), replacing the
        // built-in spl_autoload()'s include_path probe.
        //
        // The built-in used to sit BEHIND this as a fallback, for a class not
        // yet in the (TTL-cached) map. It is deliberately gone, and removing
        // it is a security fix rather than a tidy-up.
        //
        // autoload() refuses a bare CORE name -- core is namespaced now and no
        // longer re-exports itself globally (ADR 0013 §2). A refusal is only a
        // `return`, though, and PHP then carries on down the chain. The
        // built-in probes include_path by basename, include_path is built from
        // the same scan that feeds the classMap, and that scan covers the
        // plugin roots. So a plugin shipping class/host.class.php answered the
        // bare `Host` the moment core stopped answering it -- a plugin
        // silently supplying a core class to any caller the qualification
        // sweep missed. Core winning the classMap collision cannot help here:
        // core is not in that map at all, so there is no collision to resolve.
        // Proven by tests/psr4-bridge.test.php, whose probe plugin answered
        // for exactly one commit.
        //
        // What the fallback covered, it no longer needs to. include_path and
        // the map are both derived from classFileList(), so the only thing the
        // probe could find that the map could not is a file added to an
        // already-scanned directory since the cache was written -- and that
        // window is closed at both ends: Plugin::install() calls
        // forgetClassFileList(), and the cache expires on FILELIST_TTL anyway.
        spl_autoload_register([self::class, 'autoload']);

        // Last in the chain on purpose -- see the method.
        self::_registerPluginAutoloaders();

        self::_configureSessionStorage();

        /*
         * Start a session only when there is one to resume or something has
         * asked for one.
         *
         * This used to be unconditional, and 62 entry points reach it through
         * commons/base.inc.php -- including every file under service/ and
         * status/, the API and the iPXE endpoints. None of those can carry a
         * cookie back, so each request allocated a session that was written
         * once, never read again, and left for gc to clean up. A PXE boot or
         * a fleet of fog-clients polling on a timer is a steady stream of
         * them.
         *
         * Browser flows are unaffected: the login page GET declares
         * FOG_WANTS_SESSION and creates the session, and every request after
         * that presents the cookie, so the first arm matches. The API accepts
         * a session cookie when a browser sends one and falls back to token
         * auth when it does not -- both still work, because the cookie is
         * exactly the signal being tested.
         *
         * Safe because nothing on the browser-less paths uses session state:
         * there is not one $_SESSION write under service/, status/, lib/
         * reg-task, lib/client or lib/service, and setMessage() already
         * returns early when no session is active (fogbase.class.php).
         */
        /*
         * An EMPTY cookie value is not a session to resume. isset() is true for
         * "PHPSESSID=", so the gate opened for it, session.use_strict_mode found
         * no id to resume, and PHP minted a fresh empty session -- exactly the
         * per-request throwaway this gate exists to prevent, just arriving
         * through a header instead of through the unconditional session_start()
         * it replaced.
         *
         * FOGURLRequests was sending precisely that from every session-less
         * caller (fixed at source there too, but the check belongs here: this is
         * the chokepoint all 62 entry points reach, and a sender is easy to
         * reintroduce). Browsers are unaffected -- a real session presents a
         * non-empty id -- and a browser holding an emptied cookie now gets the
         * same treatment as one holding none, which is the correct answer.
         */
        $hasSession = ($_COOKIE[session_name()] ?? '') !== '';
        if (session_status() !== PHP_SESSION_ACTIVE
            && ($hasSession || defined('FOG_WANTS_SESSION'))
        ) {
            session_start();
        }
    }

    /**
     * Point PHP's session store at FOG's own directory and give it a lifetime
     * that matches FOG's own session policy.
     *
     * WHY THIS EXISTS
     *
     * FOG offers FOG_ALWAYS_LOGGED_IN and FOG_INACTIVITY_TIMEOUT ("Between 1
     * and 24 by hours") and enforces them itself in User::_isLoggedIn(). But
     * PHP deletes the session FILE out from under that on its own schedule,
     * and the stock session.gc_maxlifetime is 1440 seconds -- 24 minutes.
     * Verified identical on Fedora 44, Rocky 9.8, Rocky 10.2 and Ubuntu 26.04.
     *
     * So on every supported distro, any FOG idle policy longer than 24 minutes
     * was a lie: the collector reaped the file, session.use_strict_mode
     * (set above) then refused the browser's now-orphaned cookie and issued a
     * fresh empty session, and the user was bounced to the login page. Silently
     * -- the "You were logged out due to inactivity" toast comes from FOG's own
     * inactivity branch, which had not fired and, with FOG_ALWAYS_LOGGED_IN on,
     * cannot fire at all. Absence of that toast is the tell that PHP did it.
     *
     * WHY A PRIVATE DIRECTORY AND NOT JUST A LONGER LIFETIME
     *
     * gc_maxlifetime is a property of the save_path, not of the application:
     * PHP's collector scans the whole directory. Raising it while sharing the
     * distro's session directory imposes FOG's retention on every other PHP
     * application on the box. Taking our own directory makes the setting mean
     * what it says and confines the blast radius to FOG.
     *
     * It also fixes the ownership problem the installer works around today.
     * Session files ARE authentication tokens, so this directory is 0700 and
     * owned by the pool user -- deliberately NOT the sticky 1777 that
     * FOG_CACHE_DIR uses, because world-readable session files would let any
     * local account steal an admin session.
     *
     * WHY THE COLLECTOR SETTINGS COME WITH IT
     *
     * Owning the path means owning its garbage collection, and this is the
     * trap: Debian and Ubuntu ship session.gc_probability = 0 and clean up
     * from cron instead, via /usr/lib/php/sessionclean. That script discovers
     * what to clean by running `php -c <sapi>/php.ini` and reading
     * session.save_path out of the INI -- so a path set at runtime here is
     * invisible to it. With PHP's in-process collector disabled and the cron
     * job looking elsewhere, nothing would ever clean this directory and
     * expired session files would accumulate forever. Re-enabling the
     * in-process collector is what makes the directory self-maintaining on
     * every distro. (Confirmed on Ubuntu 26.04: gc_probability = 0, timer
     * phpsessionclean.timer present.)
     *
     * 86400 is the ceiling of FOG_INACTIVITY_TIMEOUT's own documented range,
     * chosen so PHP can never contradict whatever policy is set in the UI.
     * FOG_INACTIVITY_TIMEOUT stays the authority on when a user is logged out;
     * this is only the floor that stops PHP pre-empting it.
     *
     * @return void
     */
    private static function _configureSessionStorage(): void
    {
        // Nothing to do once a session is running -- these are all read at
        // session_start() and ini_set() on them would silently do nothing.
        if (session_status() === PHP_SESSION_ACTIVE) {
            return;
        }
        // Created by the installer, but created here too so an install whose
        // installer predates this still gets a working private store rather
        // than falling back and keeping the 24-minute bug. 0700 before any
        // session file can land in it, never afterwards.
        if (!is_dir(FOG_SESSION_DIR)) {
            @mkdir(FOG_SESSION_DIR, 0700, true);
        }
        // A directory we cannot write is worse than the shared one: every
        // session_start() would fail and nobody could log in at all. Fall back
        // to PHP's configured path, which is exactly today's behavior, and say
        // why -- a silent fallback here would look identical to the bug being
        // fixed.
        if (!is_dir(FOG_SESSION_DIR) || !is_writable(FOG_SESSION_DIR)) {
            error_log(
                sprintf(
                    'FOG: session directory %s is missing or not writable by %s;'
                    . ' falling back to the system session store, where PHP will'
                    . ' expire sessions after session.gc_maxlifetime (%ss)'
                    . ' regardless of FOG_INACTIVITY_TIMEOUT.',
                    FOG_SESSION_DIR,
                    (get_current_user() ?: 'the web user'),
                    ini_get('session.gc_maxlifetime')
                )
            );
            return;
        }
        ini_set('session.save_path', FOG_SESSION_DIR);
        ini_set('session.gc_maxlifetime', '86400');
        // See the docblock: Debian/Ubuntu disable the in-process collector.
        // These are PHP's own upstream defaults, restored for our path.
        ini_set('session.gc_probability', '1');
        ini_set('session.gc_divisor', '1000');
        // ini_set() on session.* returns false and changes nothing once output
        // has been flushed, and a pool declaring session.save_path with
        // php_admin_value rather than php_value makes it unsettable outright.
        // Either way PHP keeps the system store and its 24-minute lifetime --
        // which is the bug this method exists to fix, so it must not pass
        // unremarked. Read the value back rather than trusting the return.
        if (ini_get('session.save_path') !== FOG_SESSION_DIR) {
            error_log(
                sprintf(
                    'FOG: could not point session.save_path at %s (it is still'
                    . ' %s). A php_admin_value in the php-fpm pool, or output'
                    . ' already flushed this request, will do this. Sessions'
                    . ' will expire after %ss regardless of'
                    . ' FOG_INACTIVITY_TIMEOUT.',
                    FOG_SESSION_DIR,
                    (ini_get('session.save_path') ?: 'the system default'),
                    ini_get('session.gc_maxlifetime')
                )
            );
        }
    }

    public static function language(string $lang = 'en'): void
    {
        $validLangs = ['de' => 'DE', 'en' => 'US', 'es' => 'ES', 'eu' => 'ES', 'fr' => 'FR', 'it' => 'IT', 'pt' => 'BR', 'zh' => 'CN', 'ja' => 'JP'];
        $lang = array_key_exists($lang, $validLangs) ? $lang : 'en';
        if (session_status() === PHP_SESSION_ACTIVE) {
            $_SESSION['FOG_LANG'] = $lang;
        }
        $lang = "{$lang}_{$validLangs[$lang]}";
        $domain = 'messages';
        $apppath = realpath(__DIR__ . '/../management/languages');
        setlocale(LC_MESSAGES, $lang . ".UTF-8");
        bindtextdomain($domain, $apppath);
        textdomain($domain);
    }

    private static function _determineBasePath(): string
    {
        return dirname(__DIR__) . DS;
    }

    /** Seconds a persisted file-list cache is trusted before it is rebuilt. */
    private const FILELIST_TTL = 300;

    /**
     * The one namespace prefix the bridge in autoload() answers for.
     *
     * Deliberately a constant and not a setting. A bridge whose namespace
     * varies per install is a bridge nobody can write documentation for, and
     * one that answered for ANY prefix would make a plugin's `Vendor\Host`
     * silently resolve to core's `Host`.
     */
    private const BRIDGE_NS = 'FOG\\';

    /** In-process memo of the class-source file list. */
    private static ?array $fileList = null;

    /** In-process map of lowercased class name => absolute source path. */
    private static ?array $classMap = null;

    /**
     * In-process map of lowercased class name => absolute path under src/.
     *
     * Separate from $classMap on purpose. That map is keyed on a basename
     * with one of six *.<type>.php suffixes stripped, and it feeds
     * FOGBase::fileitems() and the include_path through classFileList();
     * PSR-4 files are bare Foo.php and belong to neither. Folding them in
     * would have meant teaching three unrelated consumers about a seventh
     * suffix to gain nothing.
     */
    private static ?array $srcMap = null;

    /**
     * In-process map of lowercased class name => fully qualified name.
     *
     * Derived from $srcMap's paths rather than scanned separately: under
     * PSR-4 the FQCN IS the path, so src/Items/Host.php is FOG\Items\Host
     * and nothing else. Deriving it means one walk, one cache and one
     * collision rule serving both maps.
     */
    private static ?array $srcClassMap = null;

    /**
     * Every autoloadable source file under BASEPATH (*.class.php, *.page.php,
     * *.event.php, *.hook.php, *.report.php, *.task.php).
     *
     * The recursive directory walk this requires is the most expensive part of
     * each request's bootstrap (it stats the whole tree) and was previously run
     * up to three times per request (here plus each HookManager/EventManager
     * scan). It is now done once: memoised for the request and persisted to a
     * short-lived JSON cache so sibling requests skip the walk entirely. The
     * cache self-heals — rebuilt whenever it is missing, older than
     * FILELIST_TTL, or fails validation — so newly deployed classes appear
     * within the TTL with no manual flush.
     *
     * @return string[] Absolute file paths.
     */
    public static function classFileList(): array
    {
        if (self::$fileList !== null) {
            return self::$fileList;
        }
        // Keyed on every scanned root, not just BASEPATH: an install that
        // gains or loses the external plugin root has a genuinely different
        // file list, and keying on BASEPATH alone would serve it the stale one
        // until the TTL expired.
        $cacheFile = FOG_CACHE_DIR . DS . 'filelist.'
            . md5(implode('|', self::_scanRoots())) . '.json';
        $cached = self::_readFileListCache($cacheFile);
        if ($cached !== null) {
            return self::$fileList = $cached;
        }
        $files = array_values(self::_scanClassFiles());
        self::_writeFileListCache($cacheFile, $files);
        return self::$fileList = $files;
    }

    /**
     * Drops the cached class-file list so the next request rescans.
     *
     * Called when code is added to or removed from a scanned root while the
     * server is running -- which only the plugin uploader does. Without it the
     * new plugin stays invisible to the autoloader until the TTL expires: its
     * manager, page and hook classes do not resolve, so installing it applies
     * no schema, registers no hooks and renders no page, while reporting
     * success. Up to five minutes of a plugin that is "installed" and inert.
     *
     * Only the current roots' entry is removed, and a failed unlink is not an
     * error: the TTL still expires on its own, so the worst case is the delay
     * this exists to avoid.
     *
     * @return void
     */
    public static function forgetClassFileList(): void
    {
        self::$fileList = null;
        self::$classMap = null;
        self::$srcMap = null;
        self::$srcClassMap = null;
        @unlink(
            FOG_CACHE_DIR . DS . 'filelist.'
            . md5(implode('|', self::_scanRoots())) . '.json'
        );
        // src/ too. Nothing writes there at runtime today -- the plugin
        // uploader is the only writer to a scanned root and it writes to
        // FOG_PLUGIN_DIR -- but this function's contract is "the tree
        // changed underneath us", and leaving one of the two maps stale
        // would make that contract true only by accident.
        @unlink(
            FOG_CACHE_DIR . DS . 'srcmap.'
            . md5(rtrim(BASEPATH, DS) . DS . 'src') . '.json'
        );
    }

    /**
     * Every PSR-4 source file under packages/web/src, by lowercased basename.
     *
     * This is the half of class resolution Composer cannot do. Composer's
     * loader claims the FOG\ prefix, so it answers FOG\Host and nothing
     * else -- but the overwhelming majority of references to a FOG class use
     * the BARE name: 168 `extends` across FOGProject/fog-plugins, and all 52
     * entries in Route::$validClasses, which is the whole REST API and which
     * spells them in lowercase. Without this, moving core into src/ makes
     * every one of those stop resolving.
     *
     * Keyed on the lowercased basename because that is the only spelling all
     * callers agree on. PHP's own class lookup is case-insensitive, so one
     * hit here serves `Host`, `host` and `HOST` alike -- see autoload().
     *
     * Deliberately NOT built from vendor/composer/autoload_classmap.php,
     * which would be free. That file is regenerated by `composer
     * dump-autoload` and fog-workflows excludes vendor/composer from
     * enforcement (the composer-binary skew reason), so a stale classmap
     * cannot fail CI. A scan cannot go stale: it heals on the same TTL as
     * classFileList() and on the same explicit invalidation.
     *
     * @return array<string, string> lowercased basename => absolute path.
     */
    public static function srcFileList(): array
    {
        if (self::$srcMap !== null) {
            return self::$srcMap;
        }
        $root = rtrim(BASEPATH, DS) . DS . 'src';
        if (!is_dir($root)) {
            // Every install predating this commit, and any checkout whose
            // tree has not been re-laid. Core still resolves through the
            // classMap below; nothing here is required for FOG to boot.
            return self::$srcMap = [];
        }
        $cacheFile = FOG_CACHE_DIR . DS . 'srcmap.' . md5($root) . '.json';
        $cached = self::_readSrcMapCache($cacheFile, $root);
        if ($cached !== null) {
            return self::$srcMap = $cached;
        }
        $map = [];
        $iterator = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($root, \FilesystemIterator::SKIP_DOTS)
        );
        foreach ($iterator as $file) {
            if (!$file->isFile() || $file->getExtension() !== 'php') {
                continue;
            }
            $key = strtolower($file->getBasename('.php'));
            if (isset($map[$key])) {
                // Two files folding to one key. Under the multi-root PSR-4
                // map Composer would resolve this by root order, silently.
                // tests/psr4-layout.test.php refuses it in the tree; this is
                // the runtime half, because a hand-placed file never went
                // through that gate.
                error_log(
                    sprintf(
                        'FOG autoloader: two files under src/ claim the class '
                        . 'name "%s" (%s and %s). Neither is served by the '
                        . 'bare-name bridge -- rename one.',
                        $key,
                        $map[$key],
                        $file->getPathname()
                    )
                );
                $map[$key] = false;
                continue;
            }
            $map[$key] = $file->getPathname();
        }
        $map = array_filter($map);
        self::_writeFileListCache($cacheFile, $map);
        return self::$srcMap = $map;
    }

    /**
     * Every class under src/, by lowercased short name => fully qualified name.
     *
     * The bare name is what the tree actually says. 520 `getClass('X')`
     * literals, `FOGController::getManager()`'s `new $short.'Manager'` and
     * all 52 lowercase entries in Route::$validClasses name a class without
     * a namespace, and every one of them resolves today only because each
     * file under src/ ends in a class_alias() re-exporting itself globally
     * (ADR 0013 §2). Retiring those aliases means the bare name has to
     * become a qualified one somewhere, and this map is that somewhere --
     * one lookup, rather than editing 520 call sites.
     *
     * Derived from srcFileList(), so it inherits that scan, its cache, its
     * TTL and its refusal to serve a name two files both claim. Under PSR-4
     * the path IS the name: src/<Bucket>/<Class>.php is FOG\<Bucket>\<Class>.
     *
     * Only src/ is covered, and deliberately. The 46 discovery-named classes
     * under lib/ carry their own class_alias and are not part of the alias
     * set being retired; plugins are global-namespace by design (ADR 0009)
     * and must keep resolving as bare names. Both fall through untouched --
     * see FOGBase::qualify().
     *
     * A useful side effect: because this is built from FOG's own tree rather
     * than from Composer's classmap, a vendored package sharing a short name
     * with a core class cannot win. `Mysqldump` is the live example --
     * FOG\Db\Mysqldump and Ifsnop\Mysqldump\Mysqldump collide in the
     * classmap and do not collide here.
     *
     * @return array<string, string> lowercased short name => FQCN.
     */
    public static function srcClassMap(): array
    {
        if (self::$srcClassMap !== null) {
            return self::$srcClassMap;
        }
        $map = [];
        foreach (self::srcFileList() as $short => $path) {
            $map[$short] = 'FOG\\' . basename(dirname($path)) . '\\'
                . basename($path, '.php');
        }
        return self::$srcClassMap = $map;
    }

    /**
     * Read a cached src/ map, or null when it is missing, stale or suspect.
     *
     * Same shape and same reasoning as _readFileListCache: FOG_CACHE_DIR is
     * world-writable and sticky, so a persisted list of paths is only trusted
     * while every entry still sits under the root it claims to describe. A
     * poisoned cache must never be able to point the autoloader somewhere
     * else.
     *
     * @param string $file the cache file
     * @param string $root the src root every value must sit under
     *
     * @return array|null
     */
    private static function _readSrcMapCache(string $file, string $root): ?array
    {
        clearstatcache(true, $file);
        if (!is_file($file)
            || (time() - (int) filemtime($file)) > self::FILELIST_TTL
        ) {
            return null;
        }
        $json = @file_get_contents($file);
        if ($json === false) {
            return null;
        }
        $data = json_decode($json, true);
        if (!is_array($data)) {
            return null;
        }
        $prefix = rtrim($root, DS) . DS;
        foreach ($data as $key => $path) {
            if (!is_string($key) || !is_string($path)
                || strncmp($path, $prefix, strlen($prefix)) !== 0
            ) {
                return null;
            }
        }
        return $data;
    }

    /**
     * Is this path plugin code rather than core code?
     *
     * Two roots count: BASEPATH/lib/plugins, where the bundled plugins are
     * unpacked by bin/fetch-plugins.sh, and FOG_PLUGIN_DIR, where an admin's
     * own plugins live (ADR 0009). Everything else under BASEPATH is core.
     *
     * Used only to break a name collision in autoload(), so it answers the
     * one question that matters there -- may this file shadow a core class --
     * and nothing else.
     *
     * @param string $path An absolute path from the class-file scan.
     *
     * @return bool
     */
    private static function _isPluginPath(string $path): bool
    {
        $roots = [rtrim(BASEPATH, DS) . DS . 'lib' . DS . 'plugins' . DS];
        if (defined('FOG_PLUGIN_DIR') && FOG_PLUGIN_DIR) {
            $roots[] = rtrim(FOG_PLUGIN_DIR, DS) . DS;
        }
        foreach ($roots as $root) {
            if (strncmp($path, $root, strlen($root)) === 0) {
                return true;
            }
        }
        return false;
    }

    /**
     * Let a plugin ship its own Composer dependencies.
     *
     * ADR 0009 left this out, and the Phase 2 plan first read that absence as
     * "plugins cannot use Composer". They can: an autoloader is an
     * spl_autoload_register callback and several coexist in one process, so a
     * plugin could always have required its own vendor/autoload.php from a
     * file body FOG already includes. What was missing is core doing it in a
     * defined order, with a defined answer when two of them disagree.
     *
     * Registered LAST, after core's Composer loader (file scope, above),
     * Initiator::autoload() and the built-in resolver. That ordering is the
     * real protection: even if the collision check below were wrong, core
     * still answers first for any name it can serve, so a plugin's vendor
     * copy cannot displace a class core provides.
     *
     * The collision check is what makes shipping a dependency in core mean
     * something. Two plugins vendoring different majors of one package both
     * declare the same class names, and whichever registered first wins --
     * the other then runs against a version it was never tested against, with
     * nothing said. For a JWT library that is a security bug rather than an
     * inconvenience, which is why core ships firebase/php-jwt and a plugin is
     * expected to depend on it instead of carrying its own.
     *
     * A refused plugin is unregistered, not fatal: the rest of FOG, and the
     * plugin's own PHP, keep working. Only its vendored classes stop
     * resolving, which is the visible failure the silent version-skew was not.
     *
     * Caveat worth knowing: Composer's `files` autoload runs at require time,
     * so a refused plugin may already have executed those before we could
     * unregister it. Preventing that would mean parsing the vendor tree
     * instead of loading it, which buys less than it costs.
     *
     * @return void
     */
    private static function _registerPluginAutoloaders(): void
    {
        if (!class_exists('\Composer\Autoload\ClassLoader', false)) {
            // No core vendor/ -- an install predating Phase 0, or a checkout
            // that never ran composer install. Nothing to register against.
            return;
        }
        $claimed = [];
        foreach (self::_composerLoaders() as $loader) {
            foreach (self::_claimsOf($loader) as $claim) {
                $claimed[$claim] = 'FOG core';
            }
        }
        foreach (self::_pluginVendorAutoloads() as $plugin => $file) {
            $loader = require $file;
            if (!$loader instanceof \Composer\Autoload\ClassLoader) {
                error_log(
                    sprintf(
                        'FOG plugin autoloader: %s did not return a Composer '
                        . 'ClassLoader. Regenerate it with `composer install`.',
                        $file
                    )
                );
                continue;
            }
            $claims = self::_claimsOf($loader);
            $conflicts = array_intersect($claims, array_keys($claimed));
            if (count($conflicts) > 0) {
                $loader->unregister();
                $first = reset($conflicts);
                error_log(
                    sprintf(
                        'FOG plugin autoloader: refusing %s -- it vendors %s, '
                        . 'already provided by %s (%d name(s) in common). Two '
                        . 'copies of one package resolve to whichever loaded '
                        . 'first, silently. Depend on the provided copy, or '
                        . 'raise it with the FOG project if core should ship '
                        . 'a different version.',
                        $file,
                        preg_replace('#^(ns|class):#', '', (string) $first),
                        $claimed[$first],
                        count($conflicts)
                    )
                );
                continue;
            }
            foreach ($claims as $claim) {
                $claimed[$claim] = $plugin;
            }
        }
    }

    /**
     * Every Composer ClassLoader currently in the autoload chain.
     *
     * Read out of spl_autoload_functions() rather than tracked in a property,
     * so it sees core's loader however it got there -- including on a tree
     * where something else required vendor/autoload.php first.
     *
     * @return \Composer\Autoload\ClassLoader[]
     */
    private static function _composerLoaders(): array
    {
        $loaders = [];
        foreach ((array) spl_autoload_functions() as $fn) {
            if (is_array($fn)
                && isset($fn[0])
                && $fn[0] instanceof \Composer\Autoload\ClassLoader
            ) {
                $loaders[] = $fn[0];
            }
        }
        return $loaders;
    }

    /**
     * The class names a loader claims, as comparable strings.
     *
     * Namespace prefixes and classmap entries both, because a package can be
     * autoloaded either way -- PSR-4 for the normal case, a classmap for one
     * that predates it. `optimize-autoloader` adds a classmap without
     * dropping the prefixes, so an optimized tree is caught by either.
     *
     * @param \Composer\Autoload\ClassLoader $loader The loader to inspect.
     *
     * @return string[]
     */
    private static function _claimsOf($loader): array
    {
        $claims = [];
        foreach (array_keys($loader->getPrefixesPsr4()) as $ns) {
            $claims[] = 'ns:' . strtolower($ns);
        }
        foreach (array_keys($loader->getPrefixes()) as $ns) {
            $claims[] = 'ns:' . strtolower($ns);
        }
        foreach (array_keys($loader->getClassMap()) as $class) {
            $claims[] = 'class:' . strtolower($class);
        }
        return array_values(array_unique($claims));
    }

    /**
     * Plugin name => its vendor/autoload.php, for every plugin that has one.
     *
     * Both plugin roots, one level deep: a plugin is a directory, its
     * dependencies are vendor/ inside it. Sorted so the order two plugins are
     * offered in is a property of their names rather than of readdir -- the
     * same per-install nondeterminism the class map had before core-wins.
     *
     * @return array<string,string>
     */
    private static function _pluginVendorAutoloads(): array
    {
        $found = [];
        $roots = [rtrim(BASEPATH, DS) . DS . 'lib' . DS . 'plugins'];
        if (defined('FOG_PLUGIN_DIR') && FOG_PLUGIN_DIR) {
            $roots[] = rtrim(FOG_PLUGIN_DIR, DS);
        }
        foreach ($roots as $root) {
            if (!is_dir($root)) {
                continue;
            }
            foreach ((array) scandir($root) as $entry) {
                if ('.' === $entry || '..' === $entry) {
                    continue;
                }
                $file = $root . DS . $entry . DS . 'vendor' . DS . 'autoload.php';
                if (is_readable($file)) {
                    $found[$entry] = $file;
                }
            }
        }
        ksort($found);
        return $found;
    }

    /**
     * Resolve a class to its source file via an O(1) name => path map.
     *
     * The built-in spl_autoload() probes every include_path directory by every
     * registered extension on each class load — tens of thousands of failed
     * stat() calls per request. This replaces that with a single hash lookup.
     *
     * The map is derived once per request from classFileList() (itself memoised
     * and TTL-cached), keyed on the lowercased basename minus its .<type>.php
     * suffix — exactly what the built-in resolver matches. A miss falls through
     * to the still-registered built-in autoloader.
     *
     * Where two files claim one key, CORE WINS and the collision is logged.
     * Keeping colliding basenames out of the scan is still the rule (see
     * _scanClassFiles) -- this is what happens when that rule is broken.
     *
     * It used to be "first one walked wins", which is readdir order and so
     * differs per install: the same code resolving to a different file on two
     * servers, silently. That is the usertracking failure documented in
     * _scanClassFiles, and it had a second edge nobody had cause to look at
     * yet -- external plugins under FOG_PLUGIN_DIR already lost to core,
     * because _scanRoots() puts BASEPATH first and first-wins does the rest,
     * but BUNDLED plugins live *inside* BASEPATH at lib/plugins, so they
     * shared one directory walk with lib/fog and the winner was a coin flip.
     * A bundled plugin shipping class/authorization.class.php could therefore
     * replace core's Authorization on some installs and not others.
     *
     * Core winning makes the two plugin roots behave the same way, which is
     * the behavior the external-plugin case already had, and it is the only
     * safe direction: a plugin must never be able to shadow a core class by
     * naming a file after it. Verified against the shipped tree at the time
     * of writing -- 396 scanned files, zero colliding basenames -- so this
     * changes no resolution that exists today.
     *
     * Note this is still NOT what the built-in does: spl_autoload() loops the
     * registered extensions on the outside and the include_path on the inside,
     * so a .class.php always beats a .report.php of the same name however the
     * directories are ordered. Two core files colliding remain unordered, and
     * are reported rather than resolved.
     *
     * A name that misses the map and carries the FOG\ prefix falls through to
     * _bridgeNamespaced() below rather than to the built-in resolver, which
     * cannot find it -- see that method.
     *
     * @param string $class The class being autoloaded.
     *
     * @return void
     */
    public static function autoload(string $class): void
    {
        if (self::$classMap === null) {
            $map = [];
            foreach (self::classFileList() as $path) {
                $base = strtolower(
                    preg_replace(
                        '#\.(report|event|class|hook|page|task)\.php$#',
                        '',
                        basename($path)
                    )
                );
                if (!isset($map[$base])) {
                    $map[$base] = $path;
                    continue;
                }
                // Collision. Let a core file displace a plugin one, and say so
                // either way -- a shadowed class is otherwise completely
                // silent, and the symptom (a method that does not exist, or
                // one that reads the wrong table) surfaces nowhere near here.
                $held = $map[$base];
                if (self::_isPluginPath($held) && !self::_isPluginPath($path)) {
                    $map[$base] = $path;
                }
                $loser = ($map[$base] === $held) ? $path : $held;
                error_log(
                    sprintf(
                        'FOG autoloader: two files claim the class name "%s"; '
                        . 'using %s and ignoring %s. Rename one -- a shadowed '
                        . 'class resolves to whichever file this rule picks, '
                        . 'not to the one the caller meant.',
                        $base,
                        $map[$base],
                        $loser
                    )
                );
            }
            self::$classMap = $map;
        }
        $key = strtolower($class);

        // Core, under src/, is answered FIRST -- before the classMap, which is
        // the plugin roots and the discovery-named files. Two reasons, and the
        // second is the load-bearing one:
        //
        //   1. It is where core lives now, so it is where core is looked for.
        //      A miss falls straight through at the cost of one isset().
        //   2. It is the ONLY thing keeping a plugin from shadowing a core
        //      class. The classMap's core-wins rule works by comparing two
        //      candidates for one key -- and core is not in that map, so
        //      there is no second candidate to prefer. A plugin shipping
        //      class/host.class.php would be the sole claimant for "host"
        //      and would win outright. Answering here, and RETURNING rather
        //      than falling through, is what restores the guarantee that
        //      rule used to provide.
        //
        // What it no longer does is satisfy the request. Every file under
        // src/ used to end with class_alias(__NAMESPACE__ . '\X', 'X'), so
        // including it declared the bare name too and the lookup succeeded.
        // Those 202 aliases are gone (ADR 0013 §2): core is reached by its
        // qualified name, from a `use` import or via FOGBase::qualify(), and
        // a bare core name is a reference that was missed by the sweep.
        //
        // So this arm exists purely to turn that into a legible error. The
        // symptom otherwise is "Class \"Host\" not found" pointing at the
        // caller, or -- worse, and silently -- a plugin's own host.class.php
        // being loaded in core's place.
        //
        // Bare names only. A namespaced request is Composer's job and it
        // already ran, at file scope, ahead of this autoloader.
        if (strpos($class, '\\') === false) {
            $map = self::srcClassMap();
            if (isset($map[$key])) {
                error_log(
                    sprintf(
                        'FOG autoloader: "%s" is a core class and core is no '
                        . 'longer aliased into the global namespace. Use %s '
                        . '-- either as a `use` import or fully qualified. '
                        . 'See ADR 0013.',
                        $class,
                        $map[$key]
                    )
                );
                return;
            }
        }

        if (isset(self::$classMap[$key])) {
            // include_once, not include. PHP does not call an autoloader
            // twice for a name it managed to declare -- but it calls it every
            // time for one it did not, and a file whose declared class name
            // does not match its filename never satisfies the lookup. The
            // second class_exists() on such a name re-included the file and
            // died on "Cannot declare class X, because the name is already in
            // use": an uncatchable fatal, so a bodyless HTTP 500. Proven with
            // a plugin shipping class/<name>manager.class.php declaring
            // something else.
            include_once self::$classMap[$key];
            return;
        }

        self::_bridgeNamespaced($class);
    }

    /**
     * Resolve a flat FOG\<Name> request that Composer cannot answer.
     *
     * Composer maps the FOG\ prefix onto src/, so `FOG\Base\FOGPage` is
     * found as src/Base/FOGPage.php and never reaches this method. Two shapes
     * still do:
     *
     *   1. The 46 discovery-named files under lib/ -- the pages, hooks,
     *      reports and the one event. They declare `namespace FOG;` flat, so
     *      `FOG\ReportManagement` maps to src/ReportManagement.php, which
     *      does not exist. PSR-4 does not do discovery and these files stay
     *      where FOGPageManager::loadPageClasses() and EventManager::load()
     *      can derive their class name from basename($file), so this is the
     *      only thing that answers a `use FOG\ReportManagement;` import.
     *      That is why this method OUTLIVED the alias retirement it was
     *      originally written to precede: the plan (docs/composer-psr4-plan.md)
     *      said to delete it alongside the 202 class_alias lines, and doing so
     *      breaks every core file that imports one of the 46.
     *   2. A miscased request. PHP class names are case-insensitive and
     *      Composer's PSR-4 prefix match is not, so `fog\host` gets here even
     *      though `FOG\Items\Host` would not.
     *
     * Flat names only. A nested request such as FOG\Items\Host is either
     * Composer's (it exists) or genuinely absent; answering it here by
     * guessing at the last segment would resolve two different classes to one
     * file.
     *
     * @param string $class The namespaced class being autoloaded.
     *
     * @return void
     */
    private static function _bridgeNamespaced(string $class): void
    {
        if (strncasecmp($class, self::BRIDGE_NS, strlen(self::BRIDGE_NS)) !== 0) {
            return;
        }
        $short = substr($class, strlen(self::BRIDGE_NS));
        if ($short === '' || strpos($short, '\\') !== false) {
            return;
        }
        $key = strtolower($short);
        // src/ before the classMap, for the same reason autoload() checks it
        // first for the bare spelling: core no longer appears in the classMap
        // at all, so a plugin shipping class/host.class.php would otherwise be
        // the sole claimant for FOG\Host and win outright.
        //
        // A core class under src/ is never FLAT, though -- every one of them
        // sits in a bucket, so FOG\Host is a wrong spelling of FOG\Items\Host
        // rather than a name to resolve. Say which it should have been and
        // return, which both diagnoses it and holds the shadowing guarantee.
        $map = self::srcClassMap();
        if (isset($map[$key])) {
            error_log(
                sprintf(
                    'FOG autoloader: "%s" is not a class. Core is namespaced '
                    . 'per bucket under src/; use %s. See ADR 0013.',
                    $class,
                    $map[$key]
                )
            );
            return;
        }
        $file = self::$classMap[$key] ?? null;
        if ($file === null) {
            return;
        }
        include_once $file;
        // Phase 3: the file may declare the namespaced name ITSELF, and then
        // alias the global one back the other way. There is nothing left to
        // bridge in that case, and aliasing again would be a "Cannot declare
        // class FOG\X, because the name is already in use" warning on every
        // single class load. Checked before the branch below, because that
        // branch's own condition is satisfied too -- the file's own
        // class_alias() has by now declared the short name.
        if (class_exists($class, false)
            || interface_exists($class, false)
            || trait_exists($class, false)
        ) {
            return;
        }
        // Checked with autoload OFF. With it on, a file whose declared class
        // name does not match its basename would re-enter autoload() for the
        // same short name and hit the "Cannot declare class X" fatal the
        // include_once above exists to avoid. Aliasing a name that was never
        // declared is itself a fatal, so both halves matter: only alias what
        // the include actually produced, and let PHP raise its own
        // catchable class-not-found for anything else.
        if (class_exists($short, false)
            || interface_exists($short, false)
            || trait_exists($short, false)
        ) {
            class_alias($short, $class);
        }
    }

    /**
     * The roots the class scan walks: the web tree, plus the external plugin
     * root when it exists.
     *
     * Both are returned with a trailing separator so a prefix comparison
     * cannot match a sibling directory whose name merely starts the same way
     * ("/opt/fog/plugins" must not accept "/opt/fog/plugins-backup").
     *
     * @return string[]
     */
    private static function _scanRoots(): array
    {
        $roots = [rtrim(BASEPATH, DS) . DS];
        if (is_dir(FOG_PLUGIN_DIR)) {
            $roots[] = rtrim(FOG_PLUGIN_DIR, DS) . DS;
        }
        return $roots;
    }

    private static function _scanClassFiles(): array
    {
        $regext = '#^.*\.(report|event|class|hook|page|task)\.php$#';
        // Walked directly rather than through a symlink from the web tree.
        // Activation does symlink an external plugin into lib/plugins so the
        // browser can fetch its js/css, but RecursiveDirectoryIterator does
        // NOT descend into a symlinked directory -- it yields the link itself
        // as one entry -- so the link is invisible here. That is deliberate:
        // scanning the real path finds each file exactly once, with no
        // FOLLOW_SYMLINKS flag that would make the walk chase every other
        // symlink in the tree as well.
        $matches = [];
        foreach (self::_scanRoots() as $root) {
            $matches = array_merge(
                $matches,
                iterator_to_array(
                    new \RegexIterator(
                        new \RecursiveIteratorIterator(
                            new \RecursiveDirectoryIterator(
                                $root,
                                \FilesystemIterator::SKIP_DOTS
                            )
                        ),
                        $regext,
                        \RegexIterator::GET_MATCH
                    ),
                    false
                )
            );
        }
        // service/ holds fog-client entry points, not class sources, and one of
        // them -- usertracking.report.php -- matches the *.report.php pattern.
        // Its map key ("usertracking") collides with lib/fog/usertracking.class
        // .php, and on a collision the file the directory walk reached first
        // wins: readdir order, so identical code fails on one install and not
        // the next. Where the entry point won, autoloading UserTracking -- which
        // only the Login History grid does -- executed it, and its
        // `require '../commons/base.inc.php'` booted FOG a second time:
        // "Cannot declare class Initiator", a bodyless 500 on that one table.
        // Nothing under service/ declares a class, so drop the directory rather
        // than special-case the one file.
        //
        // vendor/ is dropped for a related reason. Composer packages are
        // PSR-4 and use bare .php, so today none of them matches $regext at
        // all -- but "today" is the whole problem: a dependency that ships
        // one file called anything.class.php would silently claim that map
        // key, and third-party code winning a name collision against a FOG
        // class is not a failure mode worth leaving open for the sake of two
        // lines. Composer's own autoloader resolves everything under vendor/;
        // this scan must never be a second route to it.
        $entryPoints = BASEPATH . 'service' . DS;
        $vendor = BASEPATH . 'vendor' . DS;
        return array_values(
            array_filter(
                array_column($matches, 0),
                function ($path) use ($entryPoints, $vendor) {
                    return strncmp($path, $entryPoints, strlen($entryPoints)) !== 0
                        && strncmp($path, $vendor, strlen($vendor)) !== 0;
                }
            )
        );
    }

    private static function _readFileListCache(string $file): ?array
    {
        clearstatcache(true, $file);
        if (!is_file($file)
            || (time() - (int) filemtime($file)) > self::FILELIST_TTL
        ) {
            return null;
        }
        $json = @file_get_contents($file);
        if ($json === false) {
            return null;
        }
        $data = json_decode($json, true);
        if (!is_array($data) || $data === []) {
            return null;
        }
        // FOG_CACHE_DIR is world-writable (sticky). Reject any list pointing
        // outside the scanned roots so a poisoned cache can never feed foreign
        // paths to the autoloader; in-root-but-stale is healed by the TTL.
        //
        // The external plugin root is a second accepted prefix, not a hole:
        // it is only accepted while it exists, and the roots carry a trailing
        // separator so a prefix match cannot escape into a sibling directory.
        // Note this makes write access to FOG_PLUGIN_DIR equivalent to write
        // access to the code tree -- which it already is, since the autoloader
        // loads what lives there.
        //
        // The UI plugin installer (ADR 0009 tier 3) deliberately makes that
        // directory web-writable, so on a server that has turned it on this
        // guard no longer separates "the web user can write it" from "the
        // autoloader will load it". That is the accepted cost of the feature,
        // not an oversight, and it is why turning it on takes two acts: the
        // FOG_PLUGIN_UI_INSTALL_ENABLED setting AND a root-run
        // bin/fog-plugin-uploads.sh. The guard still earns its keep --
        // FOG_CACHE_DIR itself is world-writable and is never a scan root, so
        // a poisoned list still cannot point the autoloader at the cache.
        $roots = self::_scanRoots();
        foreach ($data as $path) {
            if (!is_string($path)) {
                return null;
            }
            $inRoot = false;
            foreach ($roots as $root) {
                if (strncmp($path, $root, strlen($root)) === 0) {
                    $inRoot = true;
                    break;
                }
            }
            if (!$inRoot) {
                return null;
            }
        }
        return $data;
    }

    /**
     * Persist a scan result atomically, 0600, in the world-writable cache dir.
     *
     * Takes the payload already shaped by its caller rather than reshaping
     * it: classFileList() stores a LIST of paths and srcFileList() stores a
     * MAP keyed on basename, and the array_values() that used to live here
     * silently discarded the second one's keys. A failed write is not an
     * error -- the scan simply runs again next request.
     *
     * @param string $file    the cache file
     * @param array  $payload exactly what should be encoded
     *
     * @return void
     */
    private static function _writeFileListCache(string $file, array $payload): void
    {
        $json = json_encode($payload);
        if ($json === false) {
            return;
        }
        $tmp = $file . '.' . getmypid() . '.tmp';
        if (@file_put_contents($tmp, $json, LOCK_EX) === false) {
            return;
        }
        @chmod($tmp, 0600);
        if (!@rename($tmp, $file)) {
            @unlink($tmp);
        }
    }

    public static function startInit(): void
    {
        error_reporting(E_ALL & ~E_DEPRECATED & ~E_NOTICE);
        new self;
        self::sanitizeItems();
        self::_verCheck();
        self::_extCheck();
        $globalVars = ['newService', 'json', 'node', 'sub', 'printertype', 'id', 'groupid', 'crit', 'sort', 'confirm', 'tab', 'type'];
        foreach ($globalVars as $var) {
            global $$var;
            $$var = filter_input(INPUT_GET, $var) ?? filter_input(INPUT_POST, $var);
        }
        new System();
        new Config();
        self::language($_SESSION['FOG_LANG'] ?? 'en');
    }

    public static function sanitizeItems(&$value = '')
    {
        self::setSanitize();
        $process = [&$_GET, &$_POST, &$_COOKIE, &$_SESSION];
        array_walk($process, self::$sanitizeItems);
        return $value;
    }

    private static function _verCheck(): void
    {
        if (version_compare(phpversion(), '7.4', '<')) {
            throw new \Exception('FOG Requires PHP v7.4 or higher. You have PHP v' . phpversion());
        }
    }

    private static function _extCheck(): void
    {
        $requiredExtensions = ['gettext', 'mysqli'];
        $loadedExtensions = get_loaded_extensions();
        if (count(array_intersect($requiredExtensions, $loadedExtensions)) < count($requiredExtensions)) {
            throw new \Exception(_('Missing one or more extensions.'));
        }
    }

    public static function sanitizeOutput(string $buffer): string
    {
        $search = ['/>\s+</', '/(\s)+/'];
        $replace = ['> <', '\\1'];
        return preg_replace($search, $replace, $buffer) ?? $buffer;
    }
